export interface TimingRow {
  id: string;
  name: string;
  category: string;
  peak: string;
  duration: string;
  halfLife: string;
}

function hours(value?: number): string {
  if (!value || value <= 0) return '—';
  if (value < 1) return `${Math.round(value * 60)} мин`;
  const rounded = Math.round(value * 10) / 10;
  return `${rounded} ч`;
}

/** Тайминги из справочника веществ: пик, длительность, период полувыведения. */
export const TIMINGS: TimingRow[] = SUBSTANCES.map((substance) => ({
  id: substance.id,
  name: substance.name,
  category: CATEGORY_LABELS[substance.category] ?? 'Другое',
  peak: hours(substance.peakHours),
  duration: hours(substance.durationHours),
  halfLife: hours(substance.halfLifeHours)
}));

export function searchTimings(query: string): TimingRow[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return TIMINGS;
  return TIMINGS.filter((row) => {
    const substance = SUBSTANCES.find((item) => item.id === row.id);
    const aliases = substance?.aliases?.join(' ') ?? '';
    return `${row.name} ${row.category} ${aliases}`.toLowerCase().includes(needle);
  });
}